-- Explicit administrator migration only. Runtime never owns objects or performs DDL.
CREATE SCHEMA ksu;
SET search_path=ksu,pg_catalog;
CREATE TABLE schema_version(version integer PRIMARY KEY);
INSERT INTO schema_version VALUES(1);
CREATE TABLE users(id text PRIMARY KEY,username text NOT NULL UNIQUE,name text NOT NULL,
 role text NOT NULL CHECK(role IN ('manager','inspector')),password text NOT NULL,active integer NOT NULL DEFAULT 1 CHECK(active IN (0,1)));
CREATE TABLE user_sites(user_id text REFERENCES users(id),site_id text,PRIMARY KEY(user_id,site_id));
CREATE TABLE sessions(token_hash text PRIMARY KEY,user_id text REFERENCES users(id),csrf text NOT NULL,expires double precision NOT NULL);
CREATE TABLE attempts(key text PRIMARY KEY,count integer NOT NULL,until double precision NOT NULL);
CREATE TABLE records(collection text NOT NULL CHECK(collection IN ('sites','questions','visits','inspections','findings','inventories','inventoryLines')),
 id text NOT NULL,data text NOT NULL CHECK(jsonb_typeof(data::jsonb)='object'),author_id text NOT NULL REFERENCES users(id),site_id text,
 version integer NOT NULL CHECK(version>0),created_at text NOT NULL,updated_at text NOT NULL,PRIMARY KEY(collection,id));
CREATE INDEX records_site ON records(site_id,collection);
CREATE TABLE audit(seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,at text NOT NULL,actor_id text NOT NULL,
 collection text NOT NULL,record_id text NOT NULL,operation text NOT NULL,before_json text,after_json text);
CREATE TABLE mutations(user_id text REFERENCES users(id),id text NOT NULL,body_hash text NOT NULL,PRIMARY KEY(user_id,id));
CREATE TABLE media(id text PRIMARY KEY,site_id text NOT NULL,author_id text REFERENCES users(id),content bytea NOT NULL,thumbnail bytea NOT NULL,created_at text NOT NULL);
CREATE TABLE imports(hash text PRIMARY KEY,actor_id text NOT NULL,raw_json text NOT NULL,created_at text NOT NULL);
CREATE TABLE decision_records(id text PRIMARY KEY,import_hash text NOT NULL REFERENCES imports(hash),file_sha text NOT NULL,
 sheet text NOT NULL,source_row integer NOT NULL,site_id text NOT NULL,author_id text NOT NULL REFERENCES users(id),
 data text NOT NULL CHECK(jsonb_typeof(data::jsonb)='object'),UNIQUE(file_sha,sheet,source_row));
CREATE INDEX decisions_site ON decision_records(site_id,source_row);
CREATE FUNCTION actor_id() RETURNS text LANGUAGE sql STABLE AS $$ SELECT coalesce(current_setting('ksu.actor',true),'') $$;
CREATE FUNCTION actor_role() RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path=ksu,pg_catalog AS $$
 SELECT role FROM users WHERE id=actor_id() AND active=1 $$;
CREATE FUNCTION accessible(site text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=ksu,pg_catalog AS $$
 SELECT coalesce(actor_role()='manager' OR EXISTS(SELECT 1 FROM user_sites WHERE user_id=actor_id() AND site_id=site),false) $$;
CREATE FUNCTION json_extract(value text,path text) RETURNS text LANGUAGE sql IMMUTABLE AS $$ SELECT value::jsonb ->> substring(path from 3) $$;
CREATE FUNCTION deny_change() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'immutable' USING ERRCODE='23514'; END $$;
CREATE FUNCTION record_guard() RETURNS trigger LANGUAGE plpgsql SET search_path=ksu,pg_catalog AS $$
DECLARE role text:=actor_role(); n jsonb:=NEW.data::jsonb; o jsonb;
BEGIN
 IF role IS NULL THEN RAISE EXCEPTION 'forbidden' USING ERRCODE='23514'; END IF;
 IF TG_OP='INSERT' THEN
  IF NEW.author_id IS DISTINCT FROM actor_id() OR
    (role='inspector' AND (NEW.collection IN ('sites','questions') OR NOT accessible(NEW.site_id))) OR
    (NEW.collection='inventories' AND n->>'stage' IS DISTINCT FROM 'primary') THEN
   RAISE EXCEPTION 'forbidden' USING ERRCODE='23514'; END IF;
 ELSE
  o:=OLD.data::jsonb;
  IF (NEW.author_id,NEW.collection,NEW.id,NEW.created_at) IS DISTINCT FROM (OLD.author_id,OLD.collection,OLD.id,OLD.created_at)
    OR NEW.version<>OLD.version+1 THEN RAISE EXCEPTION 'forbidden' USING ERRCODE='23514'; END IF;
  IF role='inspector' AND (NEW.collection IN ('sites','questions','inspections') OR NOT accessible(OLD.site_id) OR NOT accessible(NEW.site_id)
    OR (NEW.collection<>'visits' AND (NEW.site_id IS DISTINCT FROM OLD.site_id OR OLD.author_id<>actor_id()))
    OR (NEW.collection='visits' AND (o->>'assignedTo' IS DISTINCT FROM actor_id() OR n->>'assignedTo' IS DISTINCT FROM actor_id()))
    OR (NEW.collection='inventories' AND (n->>'stage',n->>'decision') IS DISTINCT FROM (o->>'stage',o->>'decision'))) THEN
   RAISE EXCEPTION 'forbidden' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.collection='visits' THEN
  IF n->>'siteId' IS DISTINCT FROM NEW.site_id OR NOT EXISTS(SELECT 1 FROM users u WHERE u.id=n->>'assignedTo' AND active=1
    AND (u.role='manager' OR EXISTS(SELECT 1 FROM user_sites WHERE user_id=u.id AND site_id=NEW.site_id))) THEN
   RAISE EXCEPTION 'forbidden' USING ERRCODE='23514'; END IF;
  IF TG_OP='INSERT' THEN
   IF n->>'status' IS DISTINCT FROM 'planned' OR n->>'inspectionId' IS NOT NULL OR coalesce(n->>'cancellationReason','')<>''
     OR n->>'cancelledBy' IS NOT NULL OR n->>'cancelledAt' IS NOT NULL OR (role='inspector' AND n->>'assignedTo' IS DISTINCT FROM actor_id()) THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE='23514'; END IF;
  ELSE
   IF o->>'status' IS DISTINCT FROM 'planned' OR n->>'status' IS NULL OR n->>'status' NOT IN ('planned','completed','cancelled') THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE='23514'; END IF;
   IF n->>'status'<>'planned' AND (n->>'date',n->>'siteId',n->>'kind',n->>'assignedTo',coalesce(n->>'goal','')) IS DISTINCT FROM
     (o->>'date',o->>'siteId',o->>'kind',o->>'assignedTo',coalesce(o->>'goal','')) THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE='23514'; END IF;
   IF n->>'status'='cancelled' AND (length(trim(coalesce(n->>'cancellationReason',''))) NOT BETWEEN 1 AND 1200
      OR n->>'cancelledBy' IS DISTINCT FROM actor_id() OR coalesce(n->>'cancelledAt','')='') THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE='23514'; END IF;
   IF n->>'status'='completed' AND (NOT EXISTS(SELECT 1 FROM records ins WHERE ins.collection='inspections' AND ins.id=n->>'inspectionId'
     AND ins.site_id=NEW.site_id AND ins.author_id=n->>'assignedTo') OR EXISTS(SELECT 1 FROM records v WHERE v.collection='visits'
     AND v.id<>NEW.id AND v.data::jsonb->>'inspectionId'=n->>'inspectionId')) THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE='23514'; END IF;
  END IF;
  IF n->>'status'<>'cancelled' AND (coalesce(n->>'cancellationReason','')<>'' OR n->>'cancelledBy' IS NOT NULL OR n->>'cancelledAt' IS NOT NULL)
    OR n->>'status'<>'completed' AND n->>'inspectionId' IS NOT NULL THEN
   RAISE EXCEPTION 'forbidden' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE FUNCTION record_audit() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=ksu,pg_catalog AS $$
DECLARE before_value text; after_value text:=NEW.data;
BEGIN
 IF TG_OP='UPDATE' THEN before_value:=OLD.data; END IF;
 IF NEW.collection='visits' THEN
  after_value:=(NEW.data::jsonb||jsonb_build_object('version',NEW.version))::text;
  IF TG_OP='UPDATE' THEN before_value:=(OLD.data::jsonb||jsonb_build_object('version',OLD.version))::text; END IF;
 END IF;
 INSERT INTO audit(at,actor_id,collection,record_id,operation,before_json,after_json)
 VALUES(NEW.updated_at,actor_id(),NEW.collection,NEW.id,CASE TG_OP WHEN 'INSERT' THEN 'create' ELSE 'update' END,before_value,after_value);
 RETURN NEW;
END $$;
CREATE FUNCTION decision_guard() RETURNS trigger LANGUAGE plpgsql SET search_path=ksu,pg_catalog AS $$ BEGIN
 IF actor_role() IS NULL OR NEW.author_id IS DISTINCT FROM actor_id() OR NOT accessible(NEW.site_id)
 OR NOT EXISTS(SELECT 1 FROM records WHERE collection='sites' AND id=NEW.site_id) THEN
  RAISE EXCEPTION 'forbidden' USING ERRCODE='23514'; END IF; RETURN NEW;
END $$;
CREATE FUNCTION decision_audit() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=ksu,pg_catalog AS $$ BEGIN
 INSERT INTO audit(at,actor_id,collection,record_id,operation,after_json)
 VALUES(to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),actor_id(),'decisions',NEW.id,'import',NEW.data); RETURN NEW;
END $$;
CREATE TRIGGER records_guard BEFORE INSERT OR UPDATE ON records FOR EACH ROW EXECUTE FUNCTION record_guard();
CREATE TRIGGER records_audit AFTER INSERT OR UPDATE ON records FOR EACH ROW EXECUTE FUNCTION record_audit();
CREATE TRIGGER records_no_delete BEFORE DELETE ON records FOR EACH ROW EXECUTE FUNCTION deny_change();
CREATE TRIGGER decisions_guard BEFORE INSERT ON decision_records FOR EACH ROW EXECUTE FUNCTION decision_guard();
CREATE TRIGGER decisions_audit AFTER INSERT ON decision_records FOR EACH ROW EXECUTE FUNCTION decision_audit();
CREATE TRIGGER decisions_immutable BEFORE UPDATE OR DELETE ON decision_records FOR EACH ROW EXECUTE FUNCTION deny_change();
CREATE TRIGGER audit_immutable BEFORE UPDATE OR DELETE ON audit FOR EACH ROW EXECUTE FUNCTION deny_change();
ALTER TABLE records ENABLE ROW LEVEL SECURITY;
CREATE POLICY records_read ON records FOR SELECT USING(actor_role()='manager' OR (actor_role()='inspector' AND (collection='questions' OR accessible(CASE WHEN collection='sites' THEN id ELSE site_id END))));
CREATE POLICY records_insert ON records FOR INSERT WITH CHECK(actor_role() IN ('manager','inspector') AND author_id=actor_id() AND (actor_role()='manager' OR accessible(site_id)));
CREATE POLICY records_update ON records FOR UPDATE USING(actor_role()='manager' OR (actor_role()='inspector' AND accessible(site_id) AND CASE WHEN collection='visits' THEN data::jsonb->>'assignedTo'=actor_id() ELSE author_id=actor_id() END)) WITH CHECK(accessible(site_id) OR actor_role()='manager');
ALTER TABLE media ENABLE ROW LEVEL SECURITY;
CREATE POLICY media_read ON media FOR SELECT USING(accessible(site_id));
CREATE POLICY media_insert ON media FOR INSERT WITH CHECK(accessible(site_id) AND author_id=actor_id());
ALTER TABLE decision_records ENABLE ROW LEVEL SECURITY;
CREATE POLICY decisions_read ON decision_records FOR SELECT USING(accessible(site_id));
CREATE POLICY decisions_insert ON decision_records FOR INSERT WITH CHECK(accessible(site_id) AND author_id=actor_id());
ALTER TABLE audit ENABLE ROW LEVEL SECURITY;
CREATE POLICY audit_read ON audit FOR SELECT USING(actor_role()='manager' OR EXISTS(SELECT 1 FROM records r WHERE r.collection=audit.collection AND r.id=audit.record_id AND accessible(r.site_id) AND (r.author_id=actor_id() OR r.collection='visits' AND r.data::jsonb->>'assignedTo'=actor_id())) OR EXISTS(SELECT 1 FROM decision_records d WHERE audit.collection='decisions' AND d.id=audit.record_id AND d.author_id=actor_id() AND accessible(d.site_id)));
ALTER TABLE user_sites ENABLE ROW LEVEL SECURITY;
CREATE POLICY sites_read ON user_sites FOR SELECT USING(actor_role()='manager' OR user_id=actor_id());
ALTER TABLE mutations ENABLE ROW LEVEL SECURITY;
CREATE POLICY mutations_read ON mutations FOR SELECT USING(user_id=actor_id());
CREATE POLICY mutations_insert ON mutations FOR INSERT WITH CHECK(user_id=actor_id());
-- Imports contain source files: never expose another actor's raw source through SQL.
ALTER TABLE imports ENABLE ROW LEVEL SECURITY;
CREATE POLICY imports_read ON imports FOR SELECT USING(actor_role()='manager' OR actor_id=ksu.actor_id());
CREATE POLICY imports_insert ON imports FOR INSERT WITH CHECK(actor_id=ksu.actor_id());
CREATE FUNCTION import_exists(signature text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=ksu,pg_catalog AS $$ SELECT EXISTS(SELECT 1 FROM imports WHERE hash=signature) $$;
CREATE FUNCTION import_styles(signature text) RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path=ksu,pg_catalog AS $$
 SELECT jsonb_build_object('styles',raw_json::jsonb->'styles')::text FROM imports WHERE hash=signature AND EXISTS(SELECT 1 FROM decision_records d WHERE d.import_hash=signature AND accessible(d.site_id)) $$;
-- A shared plan may change without granting access to a foreign author's audit payload.
CREATE FUNCTION state_revision() RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER SET search_path=ksu,pg_catalog AS $$
 SELECT coalesce(max(a.seq),0) FROM audit a WHERE actor_role()='manager' OR
 (actor_role()='inspector' AND (EXISTS(SELECT 1 FROM records r WHERE r.collection=a.collection AND r.id=a.record_id AND
 (r.collection='questions' OR accessible(CASE WHEN r.collection='sites' THEN r.id ELSE r.site_id END))) OR
 EXISTS(SELECT 1 FROM decision_records d WHERE a.collection='decisions' AND d.id=a.record_id AND accessible(d.site_id)))) $$;

 for nav in ['Объекты','Проверки и выезды','Нарушения','Инвентаризации','Аналитика и отчёты','Настройки']:
  page.locator('[data-nav="'+ {'Объекты':'sites','Проверки и выезды':'audits','Нарушения':'findings','Инвентаризации':'inventory','Аналитика и отчёты':'reports','Настройки':'settings'}[nav] +'"]').first.click()
  print('Nav',nav,'OK',page.locator('.page-heading h2').first.inner_text())
 page.get_by_role('button',name='Объекты',exact=True).click()
 page.get_by_role('button',name='Паспорт объекта').first.click()
 print('Detail',page.locator('.page-heading h2').first.inner_text())
 page.locator('[data-nav="findings"]').first.click()
 page.get_by_role('button',name='Изменить').first.click()
 print('Modal',page.locator('.modal-head h3').first.inner_text())
 page.get_by_role('button',name='Закрыть',exact=True).first.click()
 page.locator('[data-nav="audits"]').first.click()
 page.get_by_role('button',name='Новый выезд').click()
 print('Checklist questions',page.locator('.question-card').count())
 for b in page.locator('button[data-answer][data-value="ok"]').all(): b.click()

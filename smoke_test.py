from playwright.sync_api import sync_playwright
from pathlib import Path
import subprocess, time
server=subprocess.Popen(['python','-m','http.server','8734','--bind','127.0.0.1','--directory',str(Path(__file__).resolve().parents[1])],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
time.sleep(0.8)
url='http://127.0.0.1:8734/index.html'
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-web-security'])
 page=browser.new_page(viewport={'width':1440,'height':900},locale='ru-RU',accept_downloads=True)
 errors=[]
 page.on('pageerror',lambda e: errors.append(str(e)))
 page.evaluate("""() => { const m={}; Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>m[k]??null,setItem:(k,v)=>m[k]=String(v),removeItem:k=>delete m[k]}}); }""")

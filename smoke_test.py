 page.get_by_role('button',name='Сохранить',exact=True).click()
 print('Inventory saved',page.locator('tbody tr').count())
 page.locator('[data-nav="reports"]').first.click()
 print('Report table rows',page.locator('.table tbody tr').count())
 print('Errors',errors)

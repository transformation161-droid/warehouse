 print('Saved audits',page.locator('tbody tr').count())
 page.locator('[data-nav="inventory"]').first.click()
 page.get_by_role('button',name='Новая',exact=True).click()
 page.locator('[data-inv-cell="item"]').fill('Тестовая позиция')
 page.locator('[data-inv-cell="expected"]').fill('2')
 page.locator('[data-inv-cell="actual"]').fill('1')

'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const env={window:{},document:{addEventListener(){}},Intl,MouseEvent:class{}};
vm.runInNewContext(fs.readFileSync('release_online/writeoff_charts.js','utf8'),env);
const C=env.window.WriteoffCharts;
const metrics=v=>({cost:{value:v}});
const data={matrixPeriods:['2026-Q1','2026-Q3'],matrixSites:[{id:'s1',name:'ДЕМО · Север',metrics:metrics('12')}],matrix:[{siteId:'s1',period:'2026-Q1',metrics:metrics('12')},{siteId:'s1',period:'2026-Q3',metrics:metrics('0')}],charts:{periods:{items:[{key:'2026-Q1',metrics:metrics('12')},{key:'2026-Q3',metrics:metrics('0')}]},reasons:{items:[{key:'x',label:'ДЕМО · Износ',metrics:metrics('12'),sharePercent:'100.00'}]},tools:{items:[]}}};
assert.equal(JSON.stringify(C.periods(data).items),JSON.stringify(['2026-Q1','2026-Q2','2026-Q3']));
const s=C.series(data,{metric:'cost',top:5,sites:null})[0];
assert.equal(JSON.stringify(s.points.map(p=>p.value)),JSON.stringify(['12',null,'0']));
assert.equal((C.linePath(C.scale([12,0]),[12,null,0]).match(/M/g)||[]).length,2,'No line through an unloaded quarter');
const html=C.render(data,{});
assert.match(html,/data-wo-chart-state="missing"/);assert.match(html,/data-wo-chart-state="zero"/);
assert.match(html,/Графики аналитики/);assert.match(html,/I кв\. 2026/);assert.match(html,/III кв\. 2026/);
assert.match(html,/Доля: 100.00%/);assert.match(html,/data-wo-cross="reason"/);assert.match(html,/data-wo-site="s1"/);
assert.ok(!html.includes('NaN')&&!html.includes('Infinity'));
const many={...data,matrixSites:Array.from({length:13},(_,i)=>({id:'s'+i,name:'ДЕМО '+i,metrics:metrics(String(i))}))};
for(const [top,count] of [[5,5],[10,10],[0,13]])assert.equal(C.series(many,{metric:'cost',top,sites:null}).length,count);
assert.equal(C.series(many,{metric:'cost',top:10,sites:['s1','s3']}).length,2);
assert.equal(C.series(many,{metric:'cost',top:10,sites:[]}).length,0);
assert.ok(C.compareDecimal('100000000000000000.02','100000000000000000.01')>0,'Rank exact decimal strings before plotting');
assert.equal(C.compareDecimal('1.20','1.2'),0);
const attack={...data,matrixSites:[{id:'s1',name:'<script>alert(1)</script>',metrics:metrics('12')}]};
assert.ok(!C.render(attack,{}).includes('<script>'));assert.match(C.render(attack,{}),/&lt;script&gt;/);
const card=C.render(data,{site:'s1'});assert.match(card,/Тренд объекта/);assert.match(card,/Структура списаний объекта/);assert.ok(!card.includes('data-wo-chart="comparison"'));
assert.equal(C.periods({matrixPeriods:['2000-Q1','2026-Q3'],charts:{periods:{items:[]}}}).items.length,24);
console.log('PASS: quarter gaps, zero vs missing, line breaks, exact ranking, Top-5/10/all, selection, drill-down, escaping and compact site charts');
